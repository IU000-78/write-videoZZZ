import assert from 'node:assert/strict';
import {defaultProject,normalizeProject,distance,yawTo,aspect} from './core.js';
const original=defaultProject(),data=normalizeProject(original);
assert.equal(data.objects.filter(o=>o.type==='actor').length,5);
assert.equal(data.objects.filter(o=>o.type==='camera').length,7);
assert.equal(data.objects.find(o=>o.id===data.activeCamera).type,'camera');
assert.deepEqual(normalizeProject(JSON.parse(JSON.stringify(data))),data);
assert.equal(distance({x:0,z:0},{x:3,z:4}),5);
assert.equal(yawTo({x:0,z:0},{x:0,z:-1}),0);
assert.equal(yawTo({x:0,z:0},{x:1,z:0}),90);
assert.equal(aspect('9:16'),9/16);
assert.throws(()=>normalizeProject({...data,version:99}));
assert.throws(()=>normalizeProject({...data,objects:[data.objects[0],data.objects[0]]}));
assert.throws(()=>normalizeProject({...data,objects:[{...data.objects[0],x:NaN}]}));
assert.throws(()=>normalizeProject({...data,objects:[{...data.objects[0],type:'unknown'}]}));
assert.throws(()=>normalizeProject({...data,objects:Array(301).fill(data.objects[0])}));
const invalidTarget=normalizeProject({...data,objects:data.objects.map(o=>o.type==='camera'?{...o,target:'missing'}:o)});
assert(invalidTarget.objects.filter(o=>o.type==='camera').every(o=>o.target===null));
assert.equal(normalizeProject({...data,objects:[{...data.objects[0],x:100}]}).objects[0].x,50);
assert.equal(normalizeProject({version:1,objects:[]}).activeCamera,null);
console.log('Passed: default scene, JSON roundtrip, measurement, directions, ratios, import constraints, dangling targets, empty scene.');
